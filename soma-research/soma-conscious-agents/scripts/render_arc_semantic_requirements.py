def esc(x): return str(x).replace('|','\\|').replace('\n','<br>')
def compact_program(x):
 if isinstance(x,list): return ' '.join(f'{i+1}. {v}' for i,v in enumerate(x))
 return str(x)
def visible_actions(e):
 return [a for a,v in e['one_step'].items() if v.get('delta') and v['delta']['changed_cells']]
def repeat_actions(e): return [a for a,v in e['repeat'].items() if v['second_step_changes_state']]
def arc3_requirements(e):
 r=['unknown-goal inference','causal transition learning','persistent state','belief-state planning']
 if e['click_probe'] is not None:
  r.append('coordinate affordance learning')
  if e['click_probe']['responsive_points']==0:r.append('state-dependent affordances')
  if e['click_probe']['unique_outcomes']>1:r.append('intervention outcome clustering')
 if repeat_actions(e):r.append('history-sensitive prediction')
 if e['noncommuting_action_pairs']:r.append('action-order planning')
 initial=set(e['initial_actions'])
 if any(set(v['available_actions'])!=initial for v in e['one_step'].values()):r.append('dynamic action-space tracking')
 if any(v['frames']>1 for v in e['one_step'].values()):r.append('intra-action temporal traces')
 return r

